/** Apply a style to a partial data object — only sets fields the style defines
 *  AND that are currently empty in the data. Never overwrites user input. */
export function applyStyle<T extends Record<string, any>>(
  templateType: string,
  style: WritingStyle,
  data: T,
): T {
  const preset = TEMPLATE_STYLES[templateType]?.[style];
  if (!preset) return data;
  const next: any = { ...data };
  for (const [key, value] of Object.entries(preset)) {
    if (value && (next[key] === undefined || next[key] === null || next[key] === "")) {
      next[key] = value;
    }
  }
  return next;
}